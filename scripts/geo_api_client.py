"""
赛博GEO·诊断Pro - 云端诊断引擎调用客户端（官方 A2M 402 协议 · 两段式）

设计原则:
1. 零第三方依赖（仅 Python 标准库），可在任意 Agent 运行环境执行
2. 凭证全部走环境变量，不在代码/参数中硬编码
3. 内置 mock 模式，本地联调无需部署后端
4. 所有错误以结构化 JSON 返回，供 SKILL.md 的异常处理分支消费
5. **收费即闸门**：未付款不进入业务；付款成功后携凭证重放原请求即激活诊断

环境变量:
    GEO_API_ENDPOINT   服务端地址，如 https://geo-api.example.com（必填，mock 模式除外）
    GEO_API_TOKEN      接入凭证（必填，mock 模式除外）
    GEO_API_MOCK       设为 1 时使用内置示例数据，不发起真实请求（联调用）

用法（两段式，body 必须一致）:
    # ① 取账单（无凭证）：服务端返 402 + Payment-Needed，账单原文按 0600 落盘
    python geo_api_client.py probe --brand "品牌名" [--category "品类"] \
        [--competitors "A,B"] [--url "https://..."] [--depth 标准|深度] \
        --state-dir ".state/SESSION"

    # ② 付费后重放：携 Payment-Proof 原样重发同一请求 → 200 + 完整诊断报告
    python geo_api_client.py complete --state-dir ".state/SESSION" \
        --payment-proof-file ".state/SESSION/payment-proof.txt"

退出码:
    0 成功 | 2 配置缺失 | 3 参数缺失 | 5 服务端错误 | 6 网络错误
    7 需要付费（PAYMENT_REQUIRED：未付款 / 凭证无效或过期）——业务不得继续
"""

import argparse
import base64
import json
import os
import sys
import urllib.error
import urllib.request

MOCK_TIMEOUT = 60
REQUEST_TIMEOUT = 120


def _emit(code: int, payload: dict) -> None:
    payload["exit_code"] = code
    print(json.dumps(payload, ensure_ascii=False, indent=2))
    sys.exit(code)


