def _state_paths(state_dir: str) -> tuple:
    d = os.path.abspath(state_dir)
    os.makedirs(d, exist_ok=True)
    return (d,
            os.path.join(d, "request.json"),
            os.path.join(d, "payment-needed.txt"),
            os.path.join(d, "payment-proof.txt"))


def _write_private(path: str, text: str) -> None:
    """按 0600 落盘（支付指令原文不进入任何日志/stdout）。"""
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(text)


def _build_body(brand: str, category: str, competitors: list, url: str, depth: str) -> bytes:
    # body 只放业务参数（支付凭证走请求头 Payment-Proof，不进 body）
    return json.dumps({
        "brand": brand,
        "category": category or "",
        "competitors": competitors,
        "url": url or "",
        "depth": depth,
        "client_version": "1.1.0",
    }, ensure_ascii=False).encode("utf-8")


def _post(body_bytes: bytes, proof: str = "") -> tuple:
    """发起诊断请求；返回 (http_status, headers, parsed_body)。"""
    endpoint = os.getenv("GEO_API_ENDPOINT", "").strip()
    token = os.getenv("GEO_API_TOKEN", "").strip()
    if not endpoint or not token:
        _emit(2, {"ok": False, "error": "CONFIG_MISSING",
                  "message": "服务端接入配置缺失（GEO_API_ENDPOINT / GEO_API_TOKEN 未设置）。"
                             "本次不收费、不诊断。"})
    headers = {
        "Content-Type": "application/json; charset=utf-8",
        "Authorization": "Bearer " + token,
    }
    if proof:
        headers["Payment-Proof"] = proof
    req = urllib.request.Request(endpoint.rstrip("/") + "/v1/diagnose",
                                 data=body_bytes, method="POST", headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=REQUEST_TIMEOUT) as resp:
            raw = resp.read().decode("utf-8")
            try:
                return resp.status, dict(resp.headers), json.loads(raw)
            except json.JSONDecodeError:
                return resp.status, dict(resp.headers), {"_raw": raw[:300]}
    except urllib.error.HTTPError as e:
        raw = e.read().decode("utf-8", "replace")
        try:
            return e.code, dict(e.headers), json.loads(raw)
        except json.JSONDecodeError:
            return e.code, dict(e.headers), {"_raw": raw[:300]}
    except (urllib.error.URLError, TimeoutError) as e:
        _emit(6, {"ok": False, "error": "NETWORK_ERROR",
                  "message": "诊断服务连接失败，本次不收费。请稍后重试。",
                  "detail": str(e)})


def _handle_http_error(status: int, payload: dict) -> None:
    """把 HTTP 错误映射为结构化输出；402 统一为 exit 7（需付费才能继续）。"""
    if status == 402:
        _emit(7, {"ok": False, "error": "PAYMENT_REQUIRED",
                  "message": "尚未完成支付（或支付凭证无效/已过期），本次不产生扣费、"
                             "不执行诊断。完成支付后重试即可继续。",
                  "server_message": payload.get("message") or payload.get("error") or ""})
    if status == 401:
        _emit(2, {"ok": False, "error": "AUTH_FAILED",
                  "message": "接入凭证无效，本次不收费。请检查 GEO_API_TOKEN 配置。"})
    if status == 413:
        _emit(3, {"ok": False, "error": "PAYLOAD_TOO_LARGE",
                  "message": "请求体超过服务端上限，本次不收费。"})
    _emit(5, {"ok": False, "error": "SERVER_ERROR", "http_status": status,
              "message": "诊断服务暂时不可用，本次不收费。请稍后重试。"})


def _decode_bill(raw_bill: str) -> dict:
    """解析 Payment-Needed 账单（Base64URL JSON），只取摘要字段。"""
    try:
        pad = (-len(raw_bill)) % 4
        txt = base64.urlsafe_b64decode((raw_bill + "=" * pad)
                                      .replace("-", "+").replace("_", "/")).decode("utf-8")
        obj = json.loads(txt)
    except Exception:  # noqa: BLE001
        return {}
    protocol = obj.get("protocol") or {}
    method = obj.get("method") or {}
    return {
        "out_trade_no": protocol.get("out_trade_no"),
        "amount": protocol.get("amount"),
        "currency": protocol.get("currency"),
        "resource_id": protocol.get("resource_id"),
        "pay_before": protocol.get("pay_before"),
        "goods_name": method.get("goods_name"),
    }


def cmd_probe(args, competitors: list) -> None:
    """① 取账单：无凭证调用 → 402 + Payment-Needed → 原文 0600 落盘。"""
    if os.getenv("GEO_API_MOCK") == "1":
        _emit(0, {"ok": True, "mock": True, "stage": "probe",
                  "report": _mock_report(args.brand.strip(), args.category.strip(),
                                         competitors, args.depth)})
    d, req_path, bill_path, _ = _state_paths(args.state_dir)
    body = _build_body(args.brand.strip(), args.category.strip(), competitors,
                       args.url.strip(), args.depth)
    _write_private(req_path, body.decode("utf-8"))
    status, headers, payload = _post(body)
    if status == 200:
        # 订单已履约（例如同一订单重放）→ 直接给结果
        _emit(0, payload)
    if status != 402:
        _handle_http_error(status, payload)
    bill = ""
    for k, v in (headers or {}).items():
        if k.lower() == "payment-needed":
            bill = (v or "").strip()
            break
    if not bill:
        _emit(5, {"ok": False, "error": "SERVER_ERROR",
                  "message": "服务端未返回 Payment-Needed 账单，本次不收费。"})
    _write_private(bill_path, bill)
    summary = _decode_bill(bill)
    # 合规：完整账单原文不进 stdout（stdout 会进 Agent 日志）
    _emit(7, {"ok": False, "error": "PAYMENT_REQUIRED", "stage": "probe",
              "message": "已生成付费账单，需完成支付后才能继续诊断。"
                         "请把账单文件交给支付宝支付能力拉起收银；"
                         "用户付款后用 complete 携 Payment-Proof 继续。",
              "bill_file": bill_path,
              "request_file": req_path,
              "bill": summary})


def cmd_complete(args, competitors: list) -> None:
    """② 付费后重放：携 Payment-Proof 原样重发 probe 保存的请求体。"""
    if os.getenv("GEO_API_MOCK") == "1":
        _emit(0, {"ok": True, "mock": True, "stage": "complete",
                  "report": _mock_report(args.brand.strip(), args.category.strip(),
                                         competitors, args.depth)})
    d, req_path, bill_path, proof_default = _state_paths(args.state_dir)
    if not os.path.exists(req_path):
        _emit(3, {"ok": False, "error": "STATE_MISSING",
                  "message": "缺少状态文件，请先执行 probe 取账单。"})
    with open(req_path, "r", encoding="utf-8") as fh:
        body = fh.read().strip().encode("utf-8")
    proof = (args.payment_proof or "").strip()
    proof_path = args.payment_proof_file or proof_default
    if not proof and os.path.exists(proof_path):
        with open(proof_path, "r", encoding="utf-8") as fh:
            proof = fh.read().strip()
    if not proof:
        _emit(3, {"ok": False, "error": "MISSING_PAYMENT_PROOF",
                  "message": "缺少支付凭证（Payment-Proof）。请先完成支付，"
                             "再以 --payment-proof-file 传入凭证文件。"})
    status, headers, payload = _post(body, proof=proof)
    if status == 200:
        if not isinstance(payload, dict) or not payload.get("ok"):
            _emit(5, {"ok": False, "error": "SERVER_ERROR",
                      "message": "诊断服务返回异常，本次不收费。请稍后重试。"})
        _emit(0, payload)
    _handle_http_error(status, payload)


def main() -> None:
    parser = argparse.ArgumentParser(description="赛博GEO·诊断Pro 客户端（官方 A2M 两段式）")
    sub = parser.add_subparsers(dest="cmd", required=True)

    def add_business_args(p):
        p.add_argument("--brand", required=True, help="品牌名（必填）")
        p.add_argument("--category", default="", help="品类（选填）")
        p.add_argument("--competitors", default="", help="竞品列表，逗号分隔（选填）")
        p.add_argument("--url", default="", help="官网URL（选填）")
        p.add_argument("--depth", default="标准", choices=["标准", "深度"], help="诊断深度")

    p_probe = sub.add_parser("probe", help="取账单（无凭证）→ 402 + Payment-Needed")
    add_business_args(p_probe)
    p_probe.add_argument("--state-dir", default=".state/SESSION", help="状态目录（账单与请求体）")

    p_done = sub.add_parser("complete", help="付费后重放（携 Payment-Proof）")
    add_business_args(p_done)
    p_done.add_argument("--state-dir", default=".state/SESSION", help="状态目录（需与 probe 相同）")
    p_done.add_argument("--payment-proof", default="",
                        help="Payment-Proof 原值（注意：会进 shell 历史与进程列表，"
                             "更安全的是 --payment-proof-file）")
    p_done.add_argument("--payment-proof-file", default="",
                        help="从文件读取 Payment-Proof（推荐，凭证不经过命令行）")

    args = parser.parse_args()
    if not args.brand.strip():
        _emit(3, {"ok": False, "error": "MISSING_BRAND",
                  "message": "缺少品牌名。禁止使用占位符调用诊断服务。"})
    competitors = [c.strip() for c in args.competitors.split(",") if c.strip()]
    if args.cmd == "probe":
        cmd_probe(args, competitors)
    else:
        cmd_complete(args, competitors)


if __name__ == "__main__":
    main()
